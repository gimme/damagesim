// Regenerate src/kits/all.ts from the files in src/kits/champions (static imports for the web build).

import { readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../src/kits/champions/', import.meta.url).pathname;
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.ts'))
  .sort();
const ids = files.map((f) => f.replace(/\.ts$/, ''));
const out = `// Generated by scripts/gen-kit-index.ts — do not edit by hand.
// Curated kits by champion id. Each file in ./champions exports a ChampionKit.

import type { ChampionData } from '../engine/data-types.ts';
import type { ChampionKit } from '../engine/kit-types.ts';
${ids.map((id) => `import ${id} from './champions/${id}.ts';`).join('\n')}

export const CURATED: Record<string, ChampionKit | ((c: ChampionData) => ChampionKit)> = {
${ids.map((id) => `  ${id},`).join('\n')}
};
`;
writeFileSync(new URL('../src/kits/all.ts', import.meta.url), out);
console.log(`src/kits/all.ts: ${ids.length} curated kits`);
