// Write docs/COVERAGE.md: which champions have curated kits, which items/runes have modeled effects.
// Usage: node scripts/gen-coverage.ts

import { writeFileSync } from "node:fs";
import { loadGameData } from "../src/node/load.ts";
import { loadAllKits } from "../src/node/kits.ts";
import { getKit } from "../src/kits/index.ts";
import { listItems, listRunes } from "../src/engine/describe.ts";
import { Sim } from "../src/engine/sim.ts";

const data = loadGameData();
await loadAllKits();

const champs = data.championIndex.map((c) => ({ c, kit: getKit(data.champions[c.id]) }));
const curated = champs.filter((x) => x.kit.status !== "auto");
const items = listItems(data).filter((i) => i.tier >= 2 || i.gold >= 2000);
const runes = listRunes(data);

const describe = (id: number) => {
  const sim = new Sim(data, { champion: "Ahri", items: [id], combo: [] });
  return sim.effects.find((e) => e.source === "item" && e.id !== "item:energized-charges");
};

let md = `# Coverage (patch ${data.meta.patch})

Generated by \`node scripts/gen-coverage.ts\`.

## Champions — ${curated.length}/${champs.length} curated

| Champion | Kit | Notes |
|---|---|---|
${champs.map(({ c, kit }) => `| ${c.name} | ${kit.status} | ${(kit.notes ?? []).join(" ").replace(/\|/g, "/").slice(0, 300)} |`).join("\n")}

## Items — ${items.filter((i) => i.modeled).length} with modeled passives/actives

Items not marked "modeled" contribute their stats only (their passives are defensive, utility, or
not relevant to damage dealt to a single champion).

| Item | Gold | Modeled | What the simulator does |
|---|---|---|---|
${items.map((i) => `| ${i.name} | ${i.gold} | ${i.modeled ? "yes" : "—"} | ${i.modeled ? (describe(i.id)?.description ?? "").replace(/\|/g, "/") : i.stats} |`).join("\n")}

## Runes

| Rune | Tree | Slot | Modeled |
|---|---|---|---|
${runes.map((r) => `| ${r.name} | ${r.tree} | ${r.slot} | ${r.modeled ? "yes" : "—"} |`).join("\n")}
`;
writeFileSync(new URL("../docs/COVERAGE.md", import.meta.url), md);
console.log(`docs/COVERAGE.md: ${curated.length}/${champs.length} curated champions, ${items.filter((i) => i.modeled).length} modeled items`);
